/** CLDR plural class of a whole number in Croatian: one / few / other. */
const croatianPlural = (count: number): 'one' | 'few' | 'other' => {
  const tens = count % 100;
  const units = count % 10;
  if (units === 1 && tens !== 11) return 'one';
  if (units >= 2 && units <= 4 && !(tens >= 12 && tens <= 14)) return 'few';
  return 'other';
};

const englishCounts: Counts = {
  racesSailed: (n) => `${n} ${n === 1 ? 'race' : 'races'} sailed`,
  discards: (n) =>
    n === 0 ? 'no discards' : `${n} ${n === 1 ? 'discard' : 'discards'}`,
  entries: (n) => `${n} ${n === 1 ? 'entry' : 'entries'}`,
  boats: (n) => `${n} ${n === 1 ? 'boat' : 'boats'}`,
};

const croatianCounts: Counts = {
  racesSailed: (n) => {
    const form = {
      one: `Odjedrena ${n} utrka`,
      few: `Odjedrene ${n} utrke`,
      other: `Odjedreno ${n} utrka`,
    }[croatianPlural(n)];
    return form;
  },
  discards: (n) => {
    if (n === 0) return 'bez odbacivanja';
    const form = {
      one: 'odbačeni rezultat',
      few: 'odbačena rezultata',
      other: 'odbačenih rezultata',
    }[croatianPlural(n)];
    return `${n} ${form}`;
  },
  entries: (n) => {
    const form = { one: 'prijava', few: 'prijave', other: 'prijava' }[
      croatianPlural(n)
    ];
    return `${n} ${form}`;
  },
  boats: (n) => {
    const form = { one: 'brod', few: 'broda', other: 'brodova' }[
      croatianPlural(n)
    ];
    return `${n} ${form}`;
  },
};

export const stringsFor = (language: ExportLanguage): Strings =>
  language === 'hr' ? HR : EN;

export const countsFor = (language: ExportLanguage): Counts =>
  language === 'hr' ? croatianCounts : englishCounts;

/**
 * What a status code means, in the document's language. The code itself is
 * never translated; an unknown code gets no description (never a guess).
 */
export const penaltyDescription = (
  code: string,
  language: ExportLanguage,
): string | null => {
  const table =
    language === 'hr' ? HR_PENALTY_DESCRIPTIONS : PENALTY_DESCRIPTIONS;
  return table[code] ?? null;
};

/** The default signature labels of a language. */
export const defaultSignatureLabels = (
  language: ExportLanguage,
): [string, string] => {
  const strings = stringsFor(language);
  return [strings.raceOfficer, strings.juryChair];
};

/**
 * "Gold Fleet" / "Gold flota". A name that already says "fleet" ("Fleet 5") is
 * left as it is.
 */
export const fleetLabel = (fleet: string, language: ExportLanguage): string =>
  /fleet|flota/i.test(fleet)
    ? fleet
    : `${fleet} ${stringsFor(language).fleetWord}`;
